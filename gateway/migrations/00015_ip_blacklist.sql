CREATE TABLE IF NOT EXISTS gateway_ip_blacklist (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidr cidr NOT NULL,
    profile jsonb NOT NULL DEFAULT '{}'::jsonb,
    blocked_count bigint NOT NULL DEFAULT 0,
    last_blocked_at timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    removed_at timestamptz NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_gateway_ip_blacklist_active_cidr
    ON gateway_ip_blacklist (cidr) WHERE removed_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_gateway_ip_blacklist_active_created
    ON gateway_ip_blacklist (created_at DESC) WHERE removed_at IS NULL;

DROP TRIGGER IF EXISTS tr_yaginx_ip_blacklist_config_event ON gateway_ip_blacklist;
CREATE TRIGGER tr_yaginx_ip_blacklist_config_event
AFTER INSERT OR UPDATE OR DELETE ON gateway_ip_blacklist
FOR EACH ROW EXECUTE FUNCTION yaginx_publish_config_event();

