-- +goose Up
-- Every certificate issuance attempt (automatic or operator triggered). The
-- automatic renewal path counts rows here to enforce its per-day cap.
CREATE TABLE IF NOT EXISTS gateway_acme_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_name text NOT NULL,
    trigger text NOT NULL,
    outcome text NOT NULL DEFAULT 'started',
    order_id bigint NULL REFERENCES gateway_certificate_order(id) ON DELETE SET NULL,
    message text NOT NULL DEFAULT '',
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    finished_at timestamptz NULL,
    CONSTRAINT ck_gateway_acme_attempt_trigger CHECK (trigger IN ('auto', 'manual')),
    CONSTRAINT ck_gateway_acme_attempt_outcome CHECK (outcome IN ('started', 'success', 'failure', 'skipped'))
);
CREATE INDEX IF NOT EXISTS ix_gateway_acme_attempt_domain_started
    ON gateway_acme_attempt (domain_name, started_at DESC);

-- Per-domain automatic renewal state. Kept apart from web_domain so failure
-- bookkeeping does not emit configuration change events.
CREATE TABLE IF NOT EXISTS gateway_acme_auto_state (
    domain_name text PRIMARY KEY,
    fail_days integer NOT NULL DEFAULT 0,
    last_fail_day date NULL,
    stopped_at timestamptz NULL,
    stop_reason text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- +goose Down
DROP TABLE IF EXISTS gateway_acme_auto_state;
DROP TABLE IF EXISTS gateway_acme_attempt;
