CREATE TABLE IF NOT EXISTS gateway_certificate (
    fingerprint text PRIMARY KEY,
    dns_names text[] NOT NULL,
    issuer text NULL,
    serial_number text NULL,
    not_before timestamp with time zone NOT NULL,
    not_after timestamp with time zone NOT NULL,
    source text NOT NULL,
    status text NOT NULL DEFAULT 'active',
    encrypted_payload bytea NOT NULL,
    nonce bytea NOT NULL,
    key_version text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_gateway_certificate_dns_names
    ON gateway_certificate USING gin (dns_names);
CREATE INDEX IF NOT EXISTS ix_gateway_certificate_not_after
    ON gateway_certificate (not_after);

CREATE TABLE IF NOT EXISTS gateway_acme_account (
    directory_url text PRIMARY KEY,
    email text NOT NULL,
    account_url text NULL,
    encrypted_key bytea NOT NULL,
    nonce bytea NOT NULL,
    key_version text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gateway_certificate_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domains text[] NOT NULL,
    status text NOT NULL,
    node_id text NULL REFERENCES gateway_node(node_id),
    acme_order_url text NULL,
    attempt integer NOT NULL DEFAULT 1,
    error_message text NULL,
    next_retry_at timestamp with time zone NULL,
    started_at timestamp with time zone NOT NULL DEFAULT now(),
    finished_at timestamp with time zone NULL
);

CREATE INDEX IF NOT EXISTS ix_gateway_certificate_order_status_retry
    ON gateway_certificate_order (status, next_retry_at);

