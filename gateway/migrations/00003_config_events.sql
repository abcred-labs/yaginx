CREATE TABLE IF NOT EXISTS gateway_config_revision (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    revision bigint NOT NULL DEFAULT 0,
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);

INSERT INTO gateway_config_revision (singleton, revision)
VALUES (true, 0)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS gateway_config_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type text NOT NULL,
    resource_id text NOT NULL,
    operation text NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ck_gateway_config_event_operation CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE INDEX IF NOT EXISTS ix_gateway_config_event_created_at
    ON gateway_config_event (created_at);

-- +goose StatementBegin
CREATE OR REPLACE FUNCTION yaginx_publish_config_event()
RETURNS trigger AS $$
DECLARE
    entity jsonb;
    event_id bigint;
    event_resource_id text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        entity := to_jsonb(OLD);
    ELSE
        entity := to_jsonb(NEW);
    END IF;

    event_resource_id := COALESCE(entity ->> 'id', entity ->> 'fingerprint', entity ->> 'setting_key', '');
    INSERT INTO gateway_config_event (resource_type, resource_id, operation)
    VALUES (TG_TABLE_NAME, event_resource_id, TG_OP)
    RETURNING id INTO event_id;

    UPDATE gateway_config_revision
    SET revision = event_id, updated_at = now()
    WHERE singleton = true;

    PERFORM pg_notify('yaginx_config_changed', event_id::text);
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- +goose StatementEnd

DROP TRIGGER IF EXISTS tr_yaginx_website_config_event ON website;
CREATE TRIGGER tr_yaginx_website_config_event
AFTER INSERT OR UPDATE OR DELETE ON website
FOR EACH ROW EXECUTE FUNCTION yaginx_publish_config_event();

DROP TRIGGER IF EXISTS tr_yaginx_web_domain_config_event ON web_domain;
CREATE TRIGGER tr_yaginx_web_domain_config_event
AFTER INSERT OR UPDATE OR DELETE ON web_domain
FOR EACH ROW EXECUTE FUNCTION yaginx_publish_config_event();

