CREATE FUNCTION gateway_emit_config_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    row_data jsonb;
    object_id text;
    event_id bigint;
    schema_name text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        row_data := to_jsonb(OLD);
    ELSE
        row_data := to_jsonb(NEW);
    END IF;
    object_id := row_data ->> TG_ARGV[0];
    IF object_id IS NULL OR btrim(object_id) = '' THEN
        RAISE EXCEPTION 'configuration event key % is empty for %.%', TG_ARGV[0], TG_TABLE_SCHEMA, TG_TABLE_NAME;
    END IF;
    schema_name := TG_TABLE_SCHEMA;
    EXECUTE format('INSERT INTO %I.gateway_config_event (resource_type, resource_id, operation) VALUES ($1, $2, $3) RETURNING id', schema_name)
    INTO event_id USING TG_ARGV[1], object_id, lower(TG_OP);
    EXECUTE format('UPDATE %I.gateway_config_revision SET revision = $1, updated_at = clock_timestamp() WHERE singleton_id = 1', schema_name)
    USING event_id;
    PERFORM pg_notify('yaginx_config_changed', event_id::text);
    RETURN COALESCE(NEW, OLD);
END
$function$;
-- +goose StatementEnd

