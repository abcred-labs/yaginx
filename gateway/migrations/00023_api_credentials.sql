CREATE TABLE IF NOT EXISTS gateway_api_credential (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    purpose text NOT NULL,
    token_prefix text NOT NULL,
    token_hash bytea NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'active',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    revoked_at timestamptz,
    CONSTRAINT ck_gateway_api_credential_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_gateway_api_credential_purpose CHECK (length(btrim(purpose)) > 0),
    CONSTRAINT ck_gateway_api_credential_status CHECK (status IN ('active', 'revoked')),
    CONSTRAINT ck_gateway_api_credential_hash CHECK (octet_length(token_hash) = 32)
);

CREATE INDEX IF NOT EXISTS ix_gateway_api_credential_status
    ON gateway_api_credential (status, id);

CREATE UNIQUE INDEX IF NOT EXISTS ux_gateway_api_credential_name
    ON gateway_api_credential (name)
    WHERE status = 'active';

