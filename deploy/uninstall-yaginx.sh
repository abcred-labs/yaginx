#!/usr/bin/env bash
# Yaginx uninstaller. Counterpart of install-yaginx.sh / install-yaginx-core.sh.
#
# Detects what is installed on this host (Debian packages yaginx / yaginx-core of
# any version, the retired yaginx-upgrade worker/timer, manually copied binaries)
# and removes the program, its systemd units and files the program generated
# itself (runtime snapshots, upgrade cache/log, lock files).
# User-owned data is always kept: /etc/yaginx configuration, systemd drop-ins,
# node identity and PostgreSQL databases/roles.
set -Eeuo pipefail
trap 'echo "uninstall failed at line $LINENO: $BASH_COMMAND" >&2' ERR

usage() {
  cat <<'EOF'
Usage: uninstall-yaginx.sh [options]

  --check, --dry-run  Inspect the system and print the plan; change nothing.
  -y, --yes           Do not ask for confirmation.
  -h, --help          Show this help.

Configuration (/etc/yaginx), systemd drop-ins, node identity and databases are
never removed.
EOF
}

dry_run=0 assume_yes=0
while [ $# -gt 0 ]; do
  case "$1" in
    --check|--dry-run) dry_run=1 ;;
    -y|--yes) assume_yes=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done

if [ "$dry_run" -eq 0 ]; then
  test "$(id -u)" -eq 0 || { echo "run as root (or use --check for a read-only inspection)" >&2; exit 1; }
fi

have() { command -v "$1" >/dev/null 2>&1; }
log() { printf '==> %s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
# Runs a mutating command, or only prints it in --check mode. Failures of
# best-effort cleanup steps are reported but do not abort the uninstall.
act() {
  if [ "$dry_run" -eq 1 ]; then printf '[check] %s\n' "$*"; return 0; fi
  "$@" || warn "command failed (continuing): $*"
}

has_systemd=0
if have systemctl && [ -d /run/systemd/system ]; then has_systemd=1; fi

# Services this project has shipped across versions. yaginx-upgrade.* were removed
# from current packages but may remain from older installs.
services=(yaginx.service yaginx-core.service yaginx-upgrade.service)
timers=(yaginx-upgrade.timer)
packages=(yaginx yaginx-core)
# Generated by the program itself (safe to delete). /etc/yaginx, node/identity.json
# and snowflake.state are user/identity data and are deliberately not listed.
generated=(/run/yaginx /var/lib/yaginx/core /var/lib/yaginx/upgrade /var/lib/yaginx/runtime /var/log/yaginx/upgrade.log)
# Package-owned data directories; dpkg removes them itself. Only swept up when the
# owning package is really gone, never after a failed or partial dpkg --remove.
pkg_dirs=(/usr/share/yaginx:yaginx /usr/share/yaginx-core:yaginx-core)
kept=(/etc/yaginx /var/lib/yaginx /var/log/yaginx)
unit_dirs=(/lib/systemd/system /usr/lib/systemd/system /etc/systemd/system)
binaries=(yaginx yaginx-core)

# ---------------------------------------------------------------- inspection
installed_pkgs=()
log "Inspecting system"
if have dpkg-query; then
  for p in "${packages[@]}"; do
    status=$(dpkg-query -W -f='${db:Status-Status}' "$p" 2>/dev/null || true)
    # "config-files" = removed earlier, only the kept configuration remains.
    if [ "$status" = config-files ]; then echo "package: $p (removed, configuration kept)"; continue; fi
    case "$status" in
      installed|half-installed|half-configured|unpacked|triggers-pending|triggers-awaited)
        ver=$(dpkg-query -W -f='${Version}' "$p" 2>/dev/null || true)
        echo "package: $p $ver ($status)"
        installed_pkgs+=("$p")
        ;;
    esac
  done
else
  echo "dpkg not available: skipping package detection"
fi
[ "${#installed_pkgs[@]}" -gt 0 ] || echo "package: none installed"

found_units=()
for u in "${services[@]}" "${timers[@]}"; do
  state=not-found
  if [ "$has_systemd" -eq 1 ]; then
    state=$(systemctl show --property=LoadState --value "$u" 2>/dev/null || echo not-found)
  fi
  exists=0
  for d in "${unit_dirs[@]}"; do
    if [ -e "$d/$u" ] || [ -L "$d/$u" ]; then exists=1; fi
  done
  if [ "$state" != not-found ] || [ "$exists" -eq 1 ]; then
    active=unknown
    if [ "$has_systemd" -eq 1 ]; then active=$(systemctl is-active "$u" 2>/dev/null || true); fi
    echo "unit: $u (load=$state, active=${active:-unknown})"
    found_units+=("$u")
  fi
done

found_bins=()
for b in "${binaries[@]}"; do
  for dir in /usr/bin /usr/local/bin /usr/local/sbin /usr/sbin /opt/yaginx /opt/yaginx/bin; do
    [ -f "$dir/$b" ] || continue
    owner=$(dpkg -S "$dir/$b" 2>/dev/null | cut -d: -f1 || true)
    if [ -n "$owner" ]; then
      echo "binary: $dir/$b (owned by package $owner)"
    else
      echo "binary: $dir/$b (manual install)"
      found_bins+=("$dir/$b")
    fi
  done
done

for d in "${generated[@]}"; do
  if [ -e "$d" ]; then echo "generated: $d"; fi
done

dropins=()
for d in "${unit_dirs[@]}"; do
  for u in "${services[@]}" "${timers[@]}"; do
    if [ -d "$d/$u.d" ]; then dropins+=("$d/$u.d"); echo "drop-in: $d/$u.d"; fi
  done
done

if [ "${#installed_pkgs[@]}" -eq 0 ] && [ "${#found_units[@]}" -eq 0 ] && [ "${#found_bins[@]}" -eq 0 ]; then
  existing=0
  for d in "${generated[@]}"; do if [ -e "$d" ]; then existing=1; fi; done
  if [ "$existing" -eq 0 ]; then echo "Nothing to uninstall."; exit 0; fi
fi

# ---------------------------------------------------------------------- plan
echo
log "Plan"
echo "- stop and disable: ${services[*]} ${timers[*]}"
[ "${#installed_pkgs[@]}" -eq 0 ] || echo "- dpkg --remove: ${installed_pkgs[*]}"
echo "- remove leftover Yaginx unit files and manually installed binaries"
echo "- remove generated files: ${generated[*]}"
echo "- note: a dpkg-removed package keeps its status 'config-files' (kept configuration is reused on reinstall)"
echo "- note: processes not managed by systemd are not stopped; stop them manually"
echo "- KEEP configuration, systemd drop-ins, node identity: ${kept[*]}"
echo "- PostgreSQL databases/roles are not touched"

if [ "$dry_run" -eq 0 ] && [ "$assume_yes" -eq 0 ]; then
  [ -t 0 ] || { echo "stdin is not a terminal; re-run with --yes to confirm" >&2; exit 1; }
  printf 'Proceed? [y/N] '
  read -r reply
  case "$reply" in y|Y|yes|YES) ;; *) echo "aborted"; exit 1 ;; esac
fi

# ----------------------------------------------------------- stop and disable
log "Stopping services"
if [ "$has_systemd" -eq 1 ]; then
  # Stop timers first so a retired upgrade timer cannot start a worker mid-uninstall.
  # Only units that exist are touched, to keep the output free of noise.
  for kind in timer service; do
    for u in "${found_units[@]}"; do
      case "$u" in *."$kind") act systemctl stop "$u"; act systemctl disable "$u" ;; esac
    done
  done
fi

# ------------------------------------------------------------------- packages
if [ "${#installed_pkgs[@]}" -gt 0 ]; then
  log "Removing packages: ${installed_pkgs[*]}"
  # Both packages in one call so dpkg orders dependencies itself.
  act dpkg --remove "${installed_pkgs[@]}"
fi

# -------------------------------------------------------- leftover unit files
log "Cleaning leftover units and binaries"
for d in "${unit_dirs[@]}"; do
  for u in "${services[@]}" "${timers[@]}"; do
    if [ -e "$d/$u" ] || [ -L "$d/$u" ]; then act rm -f -- "$d/$u"; fi
  done
done
# Enablement symlinks (possibly dangling) left in *.wants directories.
for u in "${services[@]}" "${timers[@]}"; do
  for link in /etc/systemd/system/*.wants/"$u"; do
    if [ -L "$link" ]; then act rm -f -- "$link"; fi
  done
done
if [ "${#dropins[@]}" -gt 0 ]; then
  warn "keeping administrator systemd drop-ins: ${dropins[*]}"
fi
for b in "${found_bins[@]}"; do act rm -f -- "$b"; done
[ "$has_systemd" -eq 0 ] || { act systemctl daemon-reload; act systemctl reset-failed; }

# ----------------------------------------------------------------- generated
log "Removing generated files"
if have dpkg-query; then
  for entry in "${pkg_dirs[@]}"; do
    dir=${entry%%:*} pkg=${entry##*:}
    st=$(dpkg-query -W -f='${db:Status-Status}' "$pkg" 2>/dev/null || true)
    case "$st" in
      installed|half-installed|half-configured|unpacked|triggers-pending|triggers-awaited) ;;
      *) if [ -e "$dir" ] && [ "$dry_run" -eq 0 ]; then act rm -rf -- "$dir"; fi ;;
    esac
  done
fi
for d in "${generated[@]}"; do
  if [ -e "$d" ]; then act rm -rf -- "$d"; fi
done

# --------------------------------------------------------------- verification
echo
log "Verification"
left=0
if have dpkg-query; then
  for p in "${packages[@]}"; do
    s=$(dpkg-query -W -f='${db:Status-Status}' "$p" 2>/dev/null || true)
    if [ "$s" = installed ]; then echo "still installed: $p"; left=1; fi
  done
fi
if [ "$has_systemd" -eq 1 ]; then
  for u in "${services[@]}" "${timers[@]}"; do
    st=$(systemctl show --property=LoadState --value "$u" 2>/dev/null || echo not-found)
    if [ "$st" != not-found ] && [ "$st" != "" ]; then echo "unit still loaded: $u ($st)"; left=1; fi
  done
fi
if have pgrep; then
  for b in "${binaries[@]}"; do
    if pgrep -x "$b" >/dev/null 2>&1; then echo "process still running: $b"; pgrep -a -x "$b"; left=1; fi
  done
fi
for d in "${generated[@]}"; do
  if [ -e "$d" ]; then echo "still present: $d"; left=1; fi
done

if [ "$dry_run" -eq 1 ]; then
  echo "Check complete; nothing was changed."
elif [ "$left" -eq 0 ]; then
  echo "Yaginx uninstalled."
else
  echo "Uninstall finished with leftovers listed above." >&2
  exit 1
fi
