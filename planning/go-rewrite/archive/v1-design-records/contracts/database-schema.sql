DO $legacy_constraints$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'account_password_recovery'::regclass
          AND conname = 'ck_account_password_recovery_status'
    ) THEN
        ALTER TABLE account_password_recovery
            ADD CONSTRAINT ck_account_password_recovery_status
            CHECK (status IN (0, 1, 2, 3)) NOT VALID;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'account_password_recovery'::regclass
          AND conname = 'ck_account_password_recovery_failed_attempts'
    ) THEN
        ALTER TABLE account_password_recovery
            ADD CONSTRAINT ck_account_password_recovery_failed_attempts
            CHECK (failed_attempts BETWEEN 0 AND 5) NOT VALID;
    END IF;
END
$legacy_constraints$;

