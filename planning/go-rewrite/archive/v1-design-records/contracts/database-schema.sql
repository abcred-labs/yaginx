    node_id uuid NOT NULL REFERENCES gateway_node(node_id) ON DELETE RESTRICT,
    process_id uuid NOT NULL,
    host_name text NOT NULL,
    cycle_type integer NOT NULL,
    period bigint NOT NULL,
    request_qty bigint NOT NULL,
    duration_sum bigint NOT NULL,
    duration_max bigint NOT NULL,
    inbound_bytes bigint NOT NULL,
    outbound_bytes bigint NOT NULL,
    status_code jsonb NOT NULL DEFAULT '{}'::jsonb,
    spider jsonb NOT NULL DEFAULT '{}'::jsonb,
    browser jsonb NOT NULL DEFAULT '{}'::jsonb,
    os jsonb NOT NULL DEFAULT '{}'::jsonb,
